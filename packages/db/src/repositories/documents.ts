export interface DocumentListItem {
  id: string;
  filename: string;
  kind: DocumentKind;
  byte_size: number;
  reading: unknown;
  read_failure: string | null;
  text_truncated: boolean;
  t_created: Date;
  /** Display names of the current rows this document is linked to. */
  links: { kind: DocumentLinkTargetKind; id: string; name: string }[];
}

/**
 * Newest first, with each document's links resolved to display names.
 *
 * ONE query for the documents and ONE for their links, not one per document:
 * the list is the page, and N+1 on a page is the shape that stays invisible
 * until someone has uploaded two hundred files.
 */
export async function listRecent(tx: Queryable, limit = 50): Promise<DocumentListItem[]> {
  const { rows: docs } = await tx.query<Omit<DocumentListItem, "links">>(
    `SELECT id, filename, kind, byte_size, reading, read_failure, text_truncated, t_created
       FROM documents_current
      ORDER BY t_created DESC
      LIMIT $1`,
    [limit],
  );
  if (docs.length === 0) return [];

  // Names are read through the _current views: a link to a person merged or
  // undone since shows nothing rather than a stale name.
  const { rows: links } = await tx.query<{
    document_id: string;
    target_kind: DocumentLinkTargetKind;
    target_id: string;
    name: string | null;
  }>(
    `SELECT l.document_id, l.target_kind, l.target_id,
            COALESCE(p.display_name, o.name, pr.name) AS name
       FROM document_links_current l
       LEFT JOIN people_current        p  ON l.target_kind = 'person'       AND p.id  = l.target_id
       LEFT JOIN organizations_current o  ON l.target_kind = 'organization' AND o.id  = l.target_id
       LEFT JOIN projects_current      pr ON l.target_kind = 'project'      AND pr.id = l.target_id
      WHERE l.document_id = ANY($1::uuid[])
      ORDER BY l.t_created`,
    [docs.map((doc) => doc.id)],
  );

  return docs.map((doc) => ({
    ...doc,
    links: links
      .filter((link) => link.document_id === doc.id && link.name !== null)
      .map((link) => ({ kind: link.target_kind, id: link.target_id, name: link.name! })),
  }));
}
