export interface DocumentLink {
  id: string;
  document_id: string;
  target_kind: DocumentLinkTargetKind;
  target_id: string;
  inference_level: DocumentLinkInference;
  t_valid: Date;
  t_invalid: Date | null;
  t_created: Date;
  t_expired: Date | null;
}

export interface CreateDocumentLinkInput {
  documentId: string;
  targetKind: DocumentLinkTargetKind;
  targetId: string;
  inferenceLevel: DocumentLinkInference;
}

export async function createLink(tx: Queryable, input: CreateDocumentLinkInput): Promise<DocumentLink> {
  const { rows } = await tx.query<DocumentLink>(
    `INSERT INTO document_links (document_id, target_kind, target_id, inference_level)
     VALUES ($1::uuid, $2, $3::uuid, $4::inference_level)
     RETURNING *`,
    [input.documentId, input.targetKind, input.targetId, input.inferenceLevel],
  );
  return rows[0]!;
}

export async function findCurrentLink(
  tx: Queryable,
  documentId: string,
  targetKind: DocumentLinkTargetKind,
  targetId: string,
): Promise<DocumentLink | null> {
  const { rows } = await tx.query<DocumentLink>(
    `SELECT * FROM document_links_current
      WHERE document_id = $1 AND target_kind = $2 AND target_id = $3`,
    [documentId, targetKind, targetId],
  );
  return rows[0] ?? null;
}

export async function invalidateLink(tx: Queryable, id: string): Promise<void> {
  await tx.query(`UPDATE document_links SET t_invalid = now() WHERE id = $1 AND t_invalid IS NULL`, [id]);
}

