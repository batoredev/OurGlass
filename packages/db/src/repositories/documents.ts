/**
 * documents and document_links — Phase 6 ingestion (docs/PHASE-6-DESIGN.md §7).
 *
 * The rows describe a file; the file's bytes live in object storage under
 * `storage_key`. Nothing here ever sees the bytes, and nothing here decides
 * what a document means — that is the Read stage, and its answer arrives as an
 * opaque, already-validated `reading` value.
 *
 * Invalidate, never delete, as everywhere else: undo sets `t_invalid`.
 */
import type { Queryable } from "../client.js";

export type DocumentKind = "pdf" | "docx" | "xlsx" | "text" | "image";
export type DocumentLinkTargetKind = "person" | "organization" | "project";
export type DocumentLinkInference = "CONFIRMED" | "INFERRED" | "UNCERTAIN";

export interface Document {
  id: string;
  storage_key: string;
  /** As uploaded. Display only. */
  filename: string;
  kind: DocumentKind;
  content_type: string;
  byte_size: number;
  sha256: string;
  extracted_text: string | null;
  text_truncated: boolean;
  /** The Read stage's DocumentReading, or NULL when nothing could read it. */
  reading: unknown;
  read_failure: string | null;
  trace: unknown;
  source_message_id: string | null;
  t_valid: Date;
  t_invalid: Date | null;
  t_created: Date;
  t_expired: Date | null;
}

export interface CreateDocumentInput {
  /** Pre-generated by the caller so links in the same turn can reference it. */
  id?: string | null;
  storageKey: string;
  filename: string;
  kind: DocumentKind;
  contentType: string;
  byteSize: number;
  sha256: string;
  extractedText: string | null;
  textTruncated: boolean;
  reading: unknown;
  readFailure: string | null;
  trace: unknown;
  sourceMessageId: string | null;
}

export async function createDocument(tx: Queryable, input: CreateDocumentInput): Promise<Document> {
  const { rows } = await tx.query<Document>(
    `INSERT INTO documents
       (id, storage_key, filename, kind, content_type, byte_size, sha256, extracted_text,
        text_truncated, reading, read_failure, trace, source_message_id)
     VALUES (COALESCE($13::uuid, gen_random_uuid()), $1, $2, $3::document_kind, $4, $5, $6, $7,
             $8, $9::jsonb, $10, $11::jsonb, $12::uuid)
     RETURNING *`,
    [
      input.storageKey,
      input.filename,
      input.kind,
      input.contentType,
      input.byteSize,
      input.sha256,
      input.extractedText,
      input.textTruncated,
      input.reading === null || input.reading === undefined ? null : JSON.stringify(input.reading),
      input.readFailure,
      input.trace === null || input.trace === undefined ? null : JSON.stringify(input.trace),
      input.sourceMessageId,
      input.id ?? null,
    ],
  );
  return rows[0]!;
}

export async function getById(tx: Queryable, id: string): Promise<Document | null> {
  const { rows } = await tx.query<Document>(`SELECT * FROM documents WHERE id = $1`, [id]);
  return rows[0] ?? null;
}

/** The current document with these exact bytes, if any (§23 for files). */
export async function findCurrentBySha256(tx: Queryable, sha256: string): Promise<Document | null> {
  const { rows } = await tx.query<Document>(
    `SELECT * FROM documents_current WHERE sha256 = $1 ORDER BY t_created DESC LIMIT 1`,
    [sha256],
  );
  return rows[0] ?? null;
}

export async function invalidateDocument(tx: Queryable, id: string): Promise<void> {
  await tx.query(`UPDATE documents SET t_invalid = now() WHERE id = $1 AND t_invalid IS NULL`, [id]);
}

